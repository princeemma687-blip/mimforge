@dataclass
class StepAudio:
    """One step's narration audio, stored inside the lesson."""

    source: str  # "ai" | "teacher"
    label: str  # plain-words label, shown everywhere the audio goes
    data_b64: str = ""  # WAV bytes, base64
    format: str = "wav"
    duration_s: float = 0.0
    engine: str = ""  # e.g. "piper:en_US-ljspeech-medium"

    def wav_bytes(self) -> bytes:
        return base64.b64decode(self.data_b64) if self.data_b64 else b""

    def to_dict(self) -> dict:
        return {
            "source": self.source,
            "label": self.label,
            "data_b64": self.data_b64,
            "format": self.format,
            "duration_s": self.duration_s,
            "engine": self.engine,
        }

    @classmethod
    def from_dict(cls, data: Optional[dict]) -> Optional["StepAudio"]:
        if not data:
            return None
        return cls(
            source=str(data.get("source", "ai")),
            label=str(data.get("label", "")),
            data_b64=str(data.get("data_b64", "")),
            format=str(data.get("format", "wav")),
            duration_s=float(data.get("duration_s", 0.0)),
            engine=str(data.get("engine", "")),
        )

    @classmethod
    def ai(cls, wav_data: bytes, engine_id: str) -> "StepAudio":
        return cls(
            source="ai",
            label=AI_VOICE_LABEL,
            data_b64=base64.b64encode(wav_data).decode("ascii"),
            duration_s=wav_duration_s(wav_data),
            engine=engine_id,
        )

    @classmethod
    def teacher(cls, wav_data: bytes) -> "StepAudio":
        return cls(
            source="teacher",
            label=TEACHER_VOICE_LABEL,
            data_b64=base64.b64encode(wav_data).decode("ascii"),
            duration_s=wav_duration_s(wav_data),
            engine="teacher-recording",
        )


def wav_duration_s(data: bytes) -> float:
    """Duration of a WAV byte string; 0.0 when unreadable."""
    try:
        with wave.open(io.BytesIO(data), "rb") as handle:
            rate = handle.getframerate()
            return handle.getnframes() / rate if rate else 0.0
    except Exception:
        return 0.0


def wav_rms(data: bytes) -> float:
    """Root-mean-square amplitude (0..1) of a 16-bit PCM WAV; used by
    tests and the Gate v2 probe to prove audio is not silence."""
    import numpy as np

    try:
        with wave.open(io.BytesIO(data), "rb") as handle:
            frames = handle.readframes(handle.getnframes())
            width = handle.getsampwidth()
            channels = handle.getnchannels()
    except Exception:
        return 0.0
    if width != 2 or not frames:
        return 0.0
    samples = np.frombuffer(frames, dtype=np.int16).astype(np.float32)
    if channels > 1:
        samples = samples.reshape(-1, channels).mean(axis=1)
    if samples.size == 0:
        return 0.0
    return float(np.sqrt(np.mean((samples / 32768.0) ** 2)))


def _samples_to_wav(samples, sample_rate: int) -> bytes:
    import numpy as np

    pcm = (np.clip(samples, -1.0, 1.0) * 32767).astype(np.int16)
    buffer = io.BytesIO()
    with wave.open(buffer, "wb") as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(sample_rate)
        handle.writeframes(pcm.tobytes())
    return buffer.getvalue()


def convert_to_wav(data: bytes, suffix: str) -> bytes:
    """Normalise attached/recorded audio to 22050 Hz mono WAV.

    WAV input passes through untouched when FFmpeg is unavailable;
    anything else needs the bundled FFmpeg (Resource Layer)."""
    if suffix.lower() == ".wav" and wav_duration_s(data) > 0:
        return data
    ffmpeg = resources.ffmpeg_path()
    if ffmpeg is None:
        raise SpeechUnavailable(
            "This audio file needs converting, but the bundled FFmpeg "
            "could not be found. Attach a .wav file instead."
        )
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / f"input{suffix.lower() or '.bin'}"
        dst = Path(tmp) / "output.wav"
        src.write_bytes(data)
        result = subprocess.run(
            [
                str(ffmpeg), "-y", "-v", "error", "-i", str(src),
                "-vn", "-ac", "1", "-ar", "22050", str(dst),
            ],
            capture_output=True,
            timeout=120,
        )
        if result.returncode != 0 or not dst.is_file():
            raise SpeechUnavailable(
                "That audio file could not be read. Try a .wav, .mp3 "
                "or .m4a recording."
            )
        return dst.read_bytes()


# ------------------------------------------------------------- verbalising

_ONES = [
    "zero", "one", "two", "three", "four", "five", "six", "seven",
    "eight", "nine", "ten", "eleven", "twelve", "thirteen", "fourteen",
    "fifteen", "sixteen", "seventeen", "eighteen", "nineteen",
]
_TENS = [
    "", "", "twenty", "thirty", "forty", "fifty", "sixty", "seventy",
    "eighty", "ninety",
]


def _int_to_words(n: int) -> str:
    if n < 0:
        return "minus " + _int_to_words(-n)
    if n < 20:
        return _ONES[n]
    if n < 100:
        rest = n % 10
        return _TENS[n // 10] + (" " + _ONES[rest] if rest else "")
    if n < 1000:
        rest = n % 100
        return (
            _ONES[n // 100] + " hundred"
            + (" " + _int_to_words(rest) if rest else "")
        )
    if n < 1_000_000:
        rest = n % 1000
        return (
            _int_to_words(n // 1000) + " thousand"
            + (" " + _int_to_words(rest) if rest else "")
        )
    if n < 1_000_000_000:
        rest = n % 1_000_000
        return (
            _int_to_words(n // 1_000_000) + " million"
            + (" " + _int_to_words(rest) if rest else "")
        )
    return str(n)


def _number_to_words(token: str) -> str:
    """'90.5' -> 'ninety point five'; '20' -> 'twenty'."""
    if "." in token:
        whole, _, frac = token.partition(".")
        digits = " ".join(_ONES[int(d)] for d in frac if d.isdigit())
        return f"{_int_to_words(int(whole or 0))} point {digits}".strip()
    return _int_to_words(int(token))


_ORDINAL_SPECIAL = {
    "one": "first", "two": "second", "three": "third", "five": "fifth",
    "eight": "eighth", "nine": "ninth", "twelve": "twelfth",
}


def _ordinal_to_words(token: str) -> str:
    words = _int_to_words(int(token)).split()
    last = words[-1]
    if last in _ORDINAL_SPECIAL:
        words[-1] = _ORDINAL_SPECIAL[last]
    elif last.endswith("y"):
        words[-1] = last[:-1] + "ieth"
    else:
        words[-1] = last + "th"
    return " ".join(words)


