class PiperEngine:
    """The default narration voice: a Piper voice model (VITS)
    driven directly on ONNX Runtime, implementing the Piper 1.2.0
    (MIT) model interface -- begin/end markers with a pad phoneme
    before each phoneme, the voice's configured scales. No Piper
    binary and no espeak-ng are involved."""

    engine_id = "piper"

    def __init__(self, voice_dir: Path) -> None:
        self.voice_dir = Path(voice_dir)
        self.voice = self.voice_dir.name
        self._session = None
        self._phonemizer: Optional[LexiconPhonemizer] = None
        config = json.loads(
            (self.voice_dir / "model.onnx.json").read_text(encoding="utf-8")
        )
        self._config = config
        self.sample_rate = int(config["audio"]["sample_rate"])

    @property
    def id(self) -> str:
        return f"piper:{self.voice}"

    def _load(self) -> None:
        if self._session is not None:
            return
        import onnxruntime as ort

        self._phonemizer = LexiconPhonemizer.from_voice_dir(self.voice_dir)
        self._session = ort.InferenceSession(
            str(self.voice_dir / "model.onnx"),
            providers=["CPUExecutionProvider"],
        )

    def synthesize(self, text: str) -> tuple[bytes, float]:
        """Render text to (WAV bytes, duration seconds)."""
        import numpy as np

        self._load()
        assert self._session is not None and self._phonemizer is not None
        id_map = self._config["phoneme_id_map"]
        pad = id_map["_"][0]
        bos = id_map["^"][0]
        eos = id_map["$"][0]
        inference = self._config.get("inference", {})
        scales = np.array(
            [
                float(inference.get("noise_scale", 0.667)),
                float(inference.get("length_scale", 1.0)),
                float(inference.get("noise_w", 0.333)),
            ],
            dtype=np.float32,
        )
        chunks: list = []
        gap = np.zeros(int(self.sample_rate * 0.12), dtype=np.float32)
        for phonemes in self._phonemizer.sentences(text):
            ids = [bos]
            for phoneme in phonemes:
                ids += [pad, id_map[phoneme][0]]
            ids.append(eos)
            array = np.array([ids], dtype=np.int64)
            audio = self._session.run(
                None,
                {
                    "input": array,
                    "input_lengths": np.array(
                        [array.shape[1]], dtype=np.int64
                    ),
                    "scales": scales,
                },
            )[0]
            chunks.append(np.asarray(audio, dtype=np.float32).reshape(-1))
            chunks.append(gap)
        if not chunks:
            raise SpeechUnavailable("Nothing to narrate: the step text is empty.")
        samples = np.concatenate(chunks)
        wav = _samples_to_wav(samples, self.sample_rate)
        return wav, wav_duration_s(wav)


class KokoroEngine:
    """Kokoro-82M behind the same interface (plan Stage 2 gate).

    The gate PASSED on 2026-11-26 (full 9-step lesson pre-render:
    66.8 s wall / 657 MB peak RSS on the build VM against plan
    limits of 180 s / 360 s and 1.5 GB -- independently re-measured
    at Stage 2 completion; the first session measured 50.8 s /
    701 MB; Whisper round-trip intelligibility 0.935 vs Piper's
    0.802), so the model IS bundled
    and this is the preferred voice; Piper remains the guaranteed
    fallback. If the model files are ever absent, :meth:`synthesize`
    raises :class:`SpeechUnavailable`. The inference path runs
    against the model's published ONNX interface (input_ids /
    style / speed) and reads voice style vectors as raw float32
    data -- no pickled stores."""

    engine_id = "kokoro"
    sample_rate = 24000

    def __init__(self, model_dir: Optional[Path] = None) -> None:
        self.model_dir = (
            Path(model_dir) if model_dir is not None else resources.kokoro_dir()
        )
        self._session = None
        self._vocab: dict = {}

    @property
    def id(self) -> str:
        return "kokoro:kokoro-82m"

    def available(self) -> bool:
        return bool(
            self.model_dir
            and (self.model_dir / "model_fp16.onnx").is_file()
            and (self.model_dir / "tokenizer.json").is_file()
            and (self.model_dir / "voices").is_dir()
        )

    def synthesize(self, text: str) -> tuple[bytes, float]:
        import numpy as np

        if not self.available():
            raise SpeechUnavailable(
                "Kokoro-82M model files are not present on this "
                "machine. The Piper voice narrates instead."
            )
        if self._session is None:
            import onnxruntime as ort

            tokenizer = json.loads(
                (self.model_dir / "tokenizer.json").read_text(encoding="utf-8")
            )
            self._vocab = tokenizer["model"]["vocab"]
            self._session = ort.InferenceSession(
                str(self.model_dir / "model_fp16.onnx"),
                providers=["CPUExecutionProvider"],
            )
        voice_dir = resources.piper_voice_dir()
        if voice_dir is None:
            raise SpeechUnavailable("No phoneme lexicon available.")
        phonemizer = LexiconPhonemizer.from_voice_dir(voice_dir)
        style_table = np.frombuffer(
            (self.model_dir / "voices" / "af_heart.bin").read_bytes(),
            dtype=np.float32,
        ).reshape(-1, 256)
        chunks = []
        gap = np.zeros(int(self.sample_rate * 0.12), dtype=np.float32)
        for phonemes in phonemizer.sentences(text):
            chars = "".join(phonemes)
            ids = [self._vocab[c] for c in chars if c in self._vocab]
            if not ids:
                continue
            tokens = np.array([[0] + ids + [0]], dtype=np.int64)
            row = style_table[min(len(ids), len(style_table) - 1)]
            audio = self._session.run(
                None,
                {
                    "input_ids": tokens,
                    "style": row.reshape(1, 256).astype(np.float32),
                    "speed": np.ones(1, dtype=np.float32),
                },
            )[0]
            chunks.append(np.asarray(audio, dtype=np.float32).reshape(-1))
            chunks.append(gap)
        if not chunks:
            raise SpeechUnavailable("Nothing to narrate: the step text is empty.")
        wav = _samples_to_wav(np.concatenate(chunks), self.sample_rate)
        return wav, wav_duration_s(wav)


def piper_engine() -> Optional[PiperEngine]:
    """The bundled Piper engine, or None when the voice is absent."""
    voice_dir = resources.piper_voice_dir()
    if voice_dir is None:
        return None
    return PiperEngine(voice_dir)


def default_engine():
    """The preferred narration engine: Kokoro-82M when bundled (it
    passed its measured gate and is the quality voice), else the
    always-bundled Piper voice, else None."""
    kokoro = KokoroEngine()
    if kokoro.available():
        return kokoro
    return piper_engine()


def _fallback_engine(preferred) -> Optional[object]:
    """The other engine, for per-step fallback when the preferred
    engine cannot render a step."""
    if isinstance(preferred, KokoroEngine):
        return piper_engine()
    if isinstance(preferred, PiperEngine):
        kokoro = KokoroEngine()
        return kokoro if kokoro.available() else None
    return None


