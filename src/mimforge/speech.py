@dataclass
class NarrationReport:
    """What attach_narration did, for status lines and provenance."""

    engine_available: bool = False
    engine_id: str = ""
    ai_steps: int = 0
    teacher_steps: int = 0
    silent_steps: int = 0
    notes: list[str] = field(default_factory=list)

    def summary(self) -> str:
        parts = []
        if self.ai_steps:
            parts.append(f"AI VOICE ON {self.ai_steps} STEP(S)")
        if self.teacher_steps:
            parts.append(f"TEACHER VOICE ON {self.teacher_steps} STEP(S)")
        if self.silent_steps:
            parts.append(f"{self.silent_steps} STEP(S) SILENT")
        return " · ".join(parts) if parts else "NO NARRATION"


def default_cache_dir() -> Path:
    return resources.user_data_dir() / "narration-cache"


def attach_narration(
    lesson,
    *,
    teacher_audio: Optional[dict] = None,
    engine=None,
    cache_dir: Optional[Path] = None,
    progress=None,
) -> NarrationReport:
    """Render/attach narration audio for every step of a lesson.

    Runs at lesson BUILD time. Teacher recordings (``teacher_audio``
    maps step order -> a stored voice dict from the draft) always
    win over the synthetic voice. Synthetic renders are cached by
    text+engine hash under ``cache_dir`` so rebuilding a lesson is
    cheap; if the preferred engine cannot render a step, the other
    engine is tried before the step is left silent. ``progress``,
    when given, is called as ``progress(done, total)`` after each
    step so a caller can keep its UI alive during long renders.
    Never raises for a missing engine: the lesson stays silent-safe.
    """
    from .playback import LessonPackage  # local: avoid a cycle

    assert isinstance(lesson, LessonPackage)
    report = NarrationReport()
    teacher_audio = teacher_audio or {}
    if engine is None:
        try:
            engine = default_engine()
        except Exception as exc:  # noqa: BLE001 -- no engine, still build
            report.notes.append(f"engine selection failed: {exc}")
            engine = None
    engines = [e for e in (engine, _fallback_engine(engine)) if e is not None]
    report.engine_available = bool(engines)
    report.engine_id = engines[0].id if engines else ""
    cache = Path(cache_dir) if cache_dir is not None else default_cache_dir()

    total = len(lesson.steps)
    for index, step in enumerate(lesson.steps):
        stored_voice = teacher_audio.get(step.order)
        if stored_voice and stored_voice.get("data_b64"):
            audio = StepAudio.from_dict(stored_voice)
            if audio is not None:
                step.audio = audio
                report.teacher_steps += 1
        elif step.narration.strip() and engines:
            for candidate in engines:
                key = hashlib.sha256(
                    f"{candidate.id}\n{step.narration}".encode("utf-8")
                ).hexdigest()
                cache_file = cache / f"{key}.wav"
                wav_data: Optional[bytes] = None
                if cache_file.is_file():
                    wav_data = cache_file.read_bytes()
                else:
                    try:
                        wav_data, _ = candidate.synthesize(step.narration)
                        cache.mkdir(parents=True, exist_ok=True)
                        cache_file.write_bytes(wav_data)
                    except Exception as exc:  # noqa: BLE001
                        # SpeechUnavailable is the expected failure;
                        # anything else (a runtime error inside an
                        # engine) must also never break the build --
                        # the step falls back, then stays silent.
                        report.notes.append(f"step {step.order}: {exc}")
                if wav_data:
                    step.audio = StepAudio.ai(wav_data, candidate.id)
                    report.ai_steps += 1
                    break
        if step.audio is not None:
            if step.audio.duration_s > 0:
                step.duration_s = max(
                    step.duration_s or 0.0,
                    step.audio.duration_s + STEP_TAIL_S,
                )
        elif step.narration.strip():
            report.silent_steps += 1
        if progress is not None:
            progress(index + 1, total)

    lesson.provenance["narration"] = {
        "engine": report.engine_id,
        "ai_label": AI_VOICE_LABEL,
        "teacher_label": TEACHER_VOICE_LABEL,
        "ai_steps": report.ai_steps,
        "teacher_steps": report.teacher_steps,
        "silent_steps": report.silent_steps,
    }
    return report
