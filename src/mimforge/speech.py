"""Lesson narration -- speech OUT (Stage 2: talking lessons).

At LESSON BUILD time (never live on the playback path) each step's
approved narration text is rendered to audio and stored inside the
lesson package, so playback simply plays the step's audio in sync
with the machine performance. Everything is offline: the default
voice is a Piper voice model driven by this module's own synthesis
code on the bundled ONNX Runtime, and a teacher can replace any
step's synthetic voice with their own recorded voice.

Licence posture (see ``docs/SBOM.md`` for the full evidence):

- Piper 1.2.0's model interface is MIT; the bundled voice
  (``en_US-ljspeech-medium``) was trained from scratch on the
  public-domain LJ Speech dataset, per its MODEL_CARD.
- Phonemes come from a bundled word lexicon converted at packaging
  time from the MIT-licensed gruut-lang-en espeak data. Piper's
  usual phonemizer (espeak-ng) is GPL and is NOT used or bundled
  anywhere.
- Kokoro-82M sits behind the same engine interface but ships only
  if its measured pre-render gate passes (plan Stage 2); when its
  model files are absent the engine reports itself unavailable and
  Piper remains the voice.

AI labelling (product rule): every synthetic narration carries the
plain-words label :data:`AI_VOICE_LABEL`; teacher recordings carry
:data:`TEACHER_VOICE_LABEL`. The labels travel with the audio into
the UI and every export -- synthetic speech is never unlabelled.
"""

