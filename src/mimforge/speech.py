#: Ordered grapheme->phoneme rules for out-of-lexicon words. Each
#: pattern is matched at the current position; the first match wins.
#: Output phonemes are checked against the voice's phoneme set, so a
#: rule can never emit a phoneme the voice does not know.
_G2P_RULES: list[tuple[str, list[str]]] = [
    ("tion", ["ʃ", "ə", "n"]), ("sion", ["ʒ", "ə", "n"]),
    ("ture", ["t", "ʃ", "ɚ"]), ("ough", ["ɔ", "f"]),
    ("augh", ["ɔ"]), ("eigh", ["e", "ɪ"]),
    ("ch", ["t", "ʃ"]), ("sh", ["ʃ"]), ("th", ["θ"]), ("ph", ["f"]),
    ("wh", ["w"]), ("ck", ["k"]), ("ng", ["ŋ"]), ("qu", ["k", "w"]),
    ("ei", ["e", "ɪ"]), ("ey", ["e", "ɪ"]), ("ay", ["e", "ɪ"]),
    ("ai", ["e", "ɪ"]),
    ("ee", ["i"]), ("ea", ["i"]), ("oo", ["u"]), ("ou", ["a", "ʊ"]),
    ("ow", ["a", "ʊ"]), ("oi", ["ɔ", "ɪ"]), ("oy", ["ɔ", "ɪ"]),
    ("au", ["ɔ"]),
    ("aw", ["ɔ"]), ("ew", ["u"]), ("ie", ["i"]),
    ("a", ["æ"]), ("e", ["ɛ"]), ("i", ["ɪ"]), ("o", ["ɑ"]),
    ("u", ["ʌ"]), ("y", ["i"]),
    ("b", ["b"]), ("c", ["k"]), ("d", ["d"]), ("f", ["f"]),
    ("g", ["ɡ"]), ("h", ["h"]), ("j", ["d", "ʒ"]), ("k", ["k"]),
    ("l", ["l"]), ("m", ["m"]), ("n", ["n"]), ("p", ["p"]),
    ("r", ["ɹ"]), ("s", ["s"]), ("t", ["t"]), ("v", ["v"]),
    ("w", ["w"]), ("x", ["k", "s"]), ("z", ["z"]),
]

_TOKEN_RE = re.compile(
    r"(?P<num>\d+(?:\.\d+)?)(?P<ord>st|nd|rd|th)?(?P<pct>\s?%)?"
    r"|(?P<word>[A-Za-z]+(?:['’][a-z]+)?)"
)
_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+|\n+")


class LexiconPhonemizer:
    """Text -> phoneme sequences, from the bundled word lexicon.

    The lexicon was converted at packaging time from the
    MIT-licensed gruut-lang-en espeak data and pruned to the bundled
    voice's phoneme set, so every phoneme emitted here is one the
    voice knows. Numbers are verbalised in English; unknown words
    fall back to grapheme rules, then to spelling."""

    def __init__(self, lexicon: dict[str, str], phoneme_ids: dict) -> None:
        self._lexicon = lexicon
        self._known = set(phoneme_ids)

    @classmethod
    def from_voice_dir(cls, voice_dir: Path) -> "LexiconPhonemizer":
        config = json.loads(
            (voice_dir / "model.onnx.json").read_text(encoding="utf-8")
        )
        lexicon = json.loads(
            (voice_dir / "lexicon.json").read_text(encoding="utf-8")
        )
        return cls(lexicon, config["phoneme_id_map"])

    # ------------------------------------------------------------ public

    def sentences(self, text: str) -> list[list[str]]:
        """Phonemes per sentence; words separated by a ``" "``
        phoneme, clauses by two (a longer pause)."""
        text = (
            text.replace("²", " squared").replace("³", " cubed")
            .replace("=", " equals ").replace("’", "'")
        )
        out: list[list[str]] = []
        for raw in _SENTENCE_SPLIT_RE.split(text):
            raw = raw.strip()
            if not raw:
                continue
            phonemes: list[str] = []
            clauses = re.split(r"[,;:]+", raw)
            for clause_i, clause in enumerate(clauses):
                if clause_i:
                    phonemes += [" ", " "]
                words = self._clause_words(clause)
                for word_i, word_phonemes in enumerate(words):
                    if word_i:
                        phonemes.append(" ")
                    phonemes += word_phonemes
            if phonemes:
                out.append(phonemes)
        return out

    # ----------------------------------------------------------- internals

    def _clause_words(self, clause: str) -> list[list[str]]:
        words: list[list[str]] = []
        for match in _TOKEN_RE.finditer(clause):
            if match.group("num") is not None:
                spoken = (
                    _ordinal_to_words(match.group("num"))
                    if match.group("ord")
                    else _number_to_words(match.group("num"))
                )
                if match.group("pct"):
                    spoken += " percent"
                for part in spoken.split():
                    words.append(self._word_phonemes(part))
            elif match.group("word"):
                words.append(self._word_phonemes(match.group("word")))
        return words

    def _word_phonemes(self, word: str) -> list[str]:
        key = word.lower()
        entry = self._lexicon.get(key)
        if entry is None and key.endswith("'s"):
            entry = self._lexicon.get(key[:-2])
            if entry is not None:
                return entry.split() + ["z"]
        if entry is None:
            entry = self._lexicon.get(key.replace("'", ""))
        if entry is not None:
            return [
                ph for ph in entry.split() if ph in self._known
            ] or self._g2p(key)
        return self._g2p(key)

    def _g2p(self, word: str) -> list[str]:
        letters = re.sub(r"[^a-z]", "", word.lower())
        if not letters:
            return []
        out: list[str] = []
        i = 0
        while i < len(letters):
            for pattern, phonemes in _G2P_RULES:
                if letters.startswith(pattern, i) and all(
                    ph in self._known for ph in phonemes
                ):
                    out += phonemes
                    i += len(pattern)
                    break
            else:
                i += 1  # silent letter (e.g. trailing e) -- skip
        if out:
            return out
        spelled: list[str] = []
        for ch in letters:
            spelled += [
                ph for ph in _LETTER_PHONEMES.get(ch, []) if ph in self._known
            ]
        return spelled


